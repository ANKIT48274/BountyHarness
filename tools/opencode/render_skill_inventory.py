#!/usr/bin/env python3
"""Render docs/opencode/SKILLS.md from the authoritative skill.yaml files.

The generated document is a read-only inventory for OpenCode users. Skill
behavior, payloads, and safety metadata remain in .claude/skills/.
"""

from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("Error: pyyaml is required (python3 -m pip install pyyaml)")

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SKILLS_DIR = REPO_ROOT / ".claude" / "skills"
OUTPUT = REPO_ROOT / "docs" / "opencode" / "SKILLS.md"

CATEGORIES = {
    "Orchestration": ["campaign"],
    "Reconnaissance": [
        "recon", "osint", "domain-model", "asset-graph", "enrichment",
        "traffic-corpus", "program-memory", "vuln-intel", "auto-research",
    ],
    "Web application": [
        "xss", "sqli", "ssrf", "rce", "file-upload", "cors-csrf",
        "race-condition", "business-logic", "modern-browser", "http-protocol",
        "oob-infra",
    ],
    "API security": ["api", "graphql-audit"],
    "Authentication and identity": ["auth", "cross-account", "identity-domain", "persona"],
    "Cloud and CI/CD": ["cloud", "cicd-security"],
    "Mobile": ["mobile"],
    "Privilege escalation and binaries": ["privesc", "binary-analysis"],
    "Scanning and SAST": ["nuclei-scanner", "sast"],
    "Web3": ["web3-audit", "meme-coin-audit"],
    "AI/LLM security": ["ai-llm", "agent-safety"],
    "Reporting and validation": ["reporting", "impact-verifier", "triage-validation"],
    "Planning and coverage": [
        "planner", "technique-kb", "standard-catalog", "coverage",
        "evaluation-harness", "skill-scientist",
    ],
    "Scope": ["scope-manager"],
}


def workflow_tiers(data: dict) -> dict[str, int]:
    top = data.get("safety_tier")
    counts: dict[str, int] = {}
    for workflow in (data.get("workflows") or {}).values():
        tier = workflow.get("safety_tier") or top or "unspecified"
        counts[tier] = counts.get(tier, 0) + 1
    return counts


def main() -> int:
    skills = {}
    for skill_yaml in sorted(SKILLS_DIR.glob("*/skill.yaml")):
        data = yaml.safe_load(skill_yaml.read_text(encoding="utf-8")) or {}
        name = skill_yaml.parent.name
        skills[name] = data

    assigned = {name for names in CATEGORIES.values() for name in names}
    unassigned = sorted(set(skills) - assigned)
    missing = sorted(assigned - set(skills))

    lines = [
        "# BountyHarness skills in OpenCode",
        "",
        "<!-- Generated by tools/opencode/render_skill_inventory.py; do not edit by hand. -->",
        "",
        f"OpenCode discovers all **{len(skills)}** skills from `.claude/skills/` (project",
        "compatibility source). Every `SKILL.md` carries YAML frontmatter with a",
        "description so the model can advertise and load it with the `skill` tool.",
        "The instructions, payloads, scripts, runbooks, and evidence requirements are",
        "unchanged from the Claude Code originals.",
        "",
        "## Safety tier summary",
        "",
        "| Tier | Meaning | Approval |",
        "|---|---|---|",
        "| `passive` | Read-only discovery and local analysis | Not required |",
        "| `active-safe` | Low-risk, read-only target interaction | Scope required |",
        "| `intrusive` | Payloads, fuzzing, higher-risk testing | Human approval + scope |",
        "| `destructive-manual` | Data changes, privilege escalation, harmful actions | Explicit approval, never automated |",
        "",
        "Some skills omit a top-level `safety_tier` in `skill.yaml` (pre-existing);",
        "their workflow-level tiers, or the tier of the invoked workflow, still apply.",
        "Do not infer a lower tier to bypass approval.",
        "",
        "## Inventory",
        "",
        "| # | Skill | Category | Top tier | Workflow tiers | Workflows | Description |",
        "|---|---|---|---|---|---|---|",
    ]

    index = 0
    for category, names in CATEGORIES.items():
        for name in names:
            data = skills.get(name)
            if not data:
                continue
            index += 1
            top = data.get("safety_tier") or "—"
            tiers = workflow_tiers(data)
            tier_text = ", ".join(f"{k}×{v}" for k, v in sorted(tiers.items())) or "—"
            description = str(data.get("description") or "").strip().replace("\n", " ")
            description = description.replace("|", "\\|")
            workflows = len(data.get("workflows") or {})
            lines.append(
                f"| {index} | `{name}` | {category} | {top} | {tier_text} | {workflows} | {description} |"
            )

    lines += [
        "",
        "## Loading a skill",
        "",
        "In OpenCode, mention the skill as `@skill-id` or let the agent load it through",
        "the `skill` tool. The agent should still prefer the matching",
        "`bin/bb-run <skill> <workflow>` command so outputs, evidence paths, tracing,",
        "and circuit-breaker behavior stay consistent.",
        "",
    ]

    if unassigned:
        lines.append(f"Uncategorized skills: {', '.join(unassigned)}")
    if missing:
        lines.append(f"Category map references missing skills: {', '.join(missing)}")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} ({index} skills)")
    if unassigned or missing:
        print("Category map out of date; update CATEGORIES in this script.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
